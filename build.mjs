/**
 * Draws the profile from content.mjs:  node build.mjs
 *
 * GitHub strips colour and layout from a README, so each tile is drawn as a
 * small SVG picture and the README just lays the pictures out. This script
 * writes the pictures into assets/ and rewrites README.md around them.
 * The banner (assets/banner.svg) is drawn by hand and left alone.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { intro, links, sections } from './content.mjs';

/** [tile colour, text colour] — the same five as trinathpittala.com. */
const COLOURS = {
  work: ['#2b44ff', '#ffffff'],
  game: ['#ff5630', '#200700'],
  project: ['#c6f135', '#172000'],
  research: ['#b9a3ff', '#150b33'],
  education: ['#19c9a8', '#02241d'],
};

const SANS = "-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif";
const MONO = 'ui-monospace, SFMono-Regular, Menlo, Consolas, monospace';
const WIDTH = 600; // a tile's own width; the README shows it at TILE_SHOWN pixels
const PAD = 36;
const TILE_SHOWN = 415; // two fit side by side on a desktop profile; one per row on a phone

const escape = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

/** Break text into lines of at most `max` characters, on spaces. */
function wrap(text, max) {
  const lines = [''];
  for (const word of text.split(' ')) {
    const line = lines[lines.length - 1];
    if (line && line.length + word.length + 1 > max) lines.push(word);
    else lines[lines.length - 1] = line ? `${line} ${word}` : word;
  }
  return lines;
}

/** Lay a tile's text out top to bottom. Returns the SVG pieces and the height they need. */
function layout(tile) {
  const parts = [];
  let y = PAD;
  const line = (text, size, gap, extra = '') => {
    y += gap;
    parts.push(`<text x="${PAD}" y="${y}" font-size="${size}" ${extra}>${escape(text)}</text>`);
  };
  if (tile.icon) {
    const data = readFileSync(`assets/${tile.icon}`).toString('base64');
    parts.push(`<image x="${PAD}" y="${y}" width="84" height="84" href="data:image/png;base64,${data}" style="clip-path: inset(0 round 19px)"/>`);
    y += 84 + 14;
  }
  if (tile.label) line(tile.label.toUpperCase(), 16, 20, `font-family="${MONO}" font-weight="600" letter-spacing="1.5" opacity="0.8"`);
  for (const text of wrap(tile.title ?? '', 28).filter(Boolean)) line(text, 36, 42, 'font-weight="800" letter-spacing="-1"');
  if (tile.meta) line(tile.meta, 19, 32, `font-family="${MONO}" opacity="0.85"`);
  if (tile.body) y += tile.title ? 12 : 4;
  for (const text of wrap(tile.body ?? '', tile.bold ? 36 : 43).filter(Boolean)) {
    line(text, tile.bold ? 28 : 25, tile.bold ? 37 : 34, tile.bold ? 'font-weight="700" letter-spacing="-0.4"' : 'font-weight="500"');
  }
  return { parts, height: y + PAD };
}

function drawTile(tile, colour, height) {
  const [fill, ink] = COLOURS[colour];
  const arrow = tile.href ? `<text x="${WIDTH - PAD}" y="${PAD + 22}" font-size="26" font-weight="700" text-anchor="end">↗</text>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${height}" role="img" aria-label="${escape(describe(tile))}">
  <rect width="${WIDTH}" height="${height}" rx="28" fill="${fill}"/>
  <g fill="${ink}" font-family="${SANS}">${layout(tile).parts.join('')}${arrow}</g>
</svg>
`;
}

function drawPill(pill, colour) {
  const [fill, ink] = COLOURS[colour];
  const width = pill.wide ? 560 : pill.small ? 300 : 420;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} 84" role="img" aria-label="${escape(pill.label)}">
  <rect width="${width}" height="84" rx="42" fill="${fill}"/>
  <text x="${width / 2}" y="53" text-anchor="middle" fill="${ink}" font-family="${SANS}" font-size="28" font-weight="700">${escape(pill.label)} ↗</text>
</svg>
`;
}

/** The words a screen reader or a search engine gets in place of the picture. */
const describe = (tile) => [tile.title, tile.label, tile.meta, tile.body].filter(Boolean).join('. ');

/** An <img>, wrapped in a link when there is somewhere to go. */
function picture(file, alt, shown, href) {
  const img = `<img src="assets/${file}" width="${shown}" alt="${escape(alt)}">`;
  return href ? `<a href="${href}">${img}</a>` : img;
}

// ---------- Draw everything ----------

rmSync('assets/tiles', { recursive: true, force: true });
mkdirSync('assets/tiles', { recursive: true });

const readme = [
  '<!-- Generated by build.mjs from content.mjs. Edit content.mjs, then run: node build.mjs -->',
  '',
  picture('banner.svg', 'Trinath Pittala, full-stack software engineer. Now a Systems Developer at Clemson University. Two games on the App Store and Google Play. Three papers in machine learning. M.S. Computer Science.', '100%', 'https://trinathpittala.com/'),
  '',
  '<p align="center">',
  ...links.map((link) => {
    writeFileSync(`assets/tiles/link-${link.id}.svg`, drawPill({ ...link, small: true }, link.colour));
    return `  ${picture(`tiles/link-${link.id}.svg`, link.label, '19%', link.href)}`;
  }),
  '</p>',
  '',
  intro,
];

for (const section of sections) {
  // Tiles in a section share one height so the rows line up.
  const height = Math.max(0, ...section.tiles.map((tile) => layout(tile).height));
  readme.push('', `### ${section.heading}`, '', '<p align="center">');
  for (const tile of section.tiles) {
    writeFileSync(`assets/tiles/${tile.id}.svg`, drawTile(tile, tile.colour ?? section.colour, height));
    readme.push(`  ${picture(`tiles/${tile.id}.svg`, describe(tile), TILE_SHOWN, tile.href)}`);
  }
  for (const pill of section.pills ?? []) {
    writeFileSync(`assets/tiles/${pill.id}.svg`, drawPill(pill, pill.colour ?? section.colour));
    readme.push(`  ${picture(`tiles/${pill.id}.svg`, pill.label, pill.wide ? 274 : 205, pill.href)}`);
  }
  readme.push('</p>');
}

writeFileSync('README.md', `${readme.join('\n')}\n`);
console.log(`Drew ${sections.reduce((n, s) => n + s.tiles.length + (s.pills?.length ?? 0), links.length)} pictures and rewrote README.md`);
